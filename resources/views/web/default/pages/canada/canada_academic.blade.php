  <h2 style="color: #2c3e50;">Academic Integrity Charter in the E-Learning Environment</h2>

  <p>
    Positive Interaction's positive training interaction in the e-learning environment is based on a policy of academic values, honesty, and integrity. Trainees and trainers must uphold these values, reflecting them in behaviors and ethics during training and exams. Cheating, identity fraud, or any violation of academic integrity in the e-learning environment is strictly prohibited.
  </p>

  <h3 style="color: #34495e;">Cheating Prevention Techniques and Identity Fraud:</h3>
  <ul>
    <li>During exams, trainees are not allowed to communicate with each other.</li>
    <li>Retaining books, papers, or referring to any books, papers, or information sources (whether paper or electronic) without explicit permission from the trainer is prohibited.</li>
  </ul>

  <h3 style="color: #34495e;">Written Assignments:</h3>
  <ul>
    <li>Submission of any written assignment is the responsibility of the trainee.</li>
    <li>Trainees must submit their work personally to the course trainer or their designated assistant within the specified time.</li>
    <li>Collaboration in course assignments or task completion is not allowed without explicit permission from the trainer.</li>
    <li>Trainees should familiarize themselves with all relevant course regulations and consult their course trainer and advisors regarding assignment preparation and submission.</li>
  </ul>

  <h3 style="color: #34495e;">Other Actions:</h3>
  <ol>
    <li>Trainees who sell lectures, notes, papers, or research papers during their enrollment or accept monetary compensation for their work without prior written approval from the training center will face disciplinary measures.</li>
    <li>Trainees providing models or petitions with falsified information, forged signatures, or misleading information will be subject to disciplinary actions.</li>
    <li>Tests are designed to cover all aspects and outcomes of the course and primarily assess the trainee's understanding of the course and training outcomes.</li>
    <li>Emphasis is placed on projects and oral tests in the evaluation process.</li>
    <li>Trainees may be required to operate their video cameras in some cases to verify their identity, and camera verification may be requested during the trainee's presence to ensure no unauthorized individuals or materials are present.</li>
    <li>Wearing headphones during exams is prohibited.</li>
    <li>Comprehensive awareness is provided for trainees and trainers regarding systems, regulations, and penalties for cheating and identity fraud.</li>
    <li>Use of technology to prevent opening any other programs during the test and to prevent copying of the test.</li>
    <li>Presentation of test instructions, rules, and cheating and identity fraud regulations during the test.</li>
  </ol>

  <h3 style="color: #34495e;">Violations:</h3>
  <ol>
    <li>Impersonating someone else to take the test.</li>
    <li>Negatively impacting the progress of the test, whether the intent is cheating or for any other reason.</li>
    <li>Disrespect towards colleagues or test supervisors.</li>
    <li>Cheating or attempting to cheat on the test (e.g., communicating with other trainees, retaining books or papers, referring to any books or papers, or accessing any information sources without explicit permission).</li>
    <li>Violating test instructions or the test supervisor's directives, such as refusing to open the camera or not ceasing prohibited behavior after warning.</li>
  </ol>

  <h3 style="color: #34495e;">Penalties:</h3>
  <ul>
    <li>Prohibition from entering the test.</li>
    <li>Failure in the test.</li>
    <li>Cancellation of previous test results.</li>
    <li>Prohibition from taking further tests.</li>
  </ul>

  <h3 style="color: #34495e;">Investigation Procedures for Violations:</h3>
  <ol>
    <li>The test supervisor prepares a detailed report including all facts. The violator and any witnesses are requested to write statements to be submitted to the Test Committee, and these are signed on the report.</li>
    <li>The test supervisors submit the report and the Test Committee's recommendations regarding the proven violation to the Chairman of the Test Committee.</li>
    <li>The Test Committee investigates the violation and submits its recommendations, accompanied by evidence, to the Chairman of the Test Committee.</li>
    <li>Upon confirming a violation, the Test Committee issues the appropriate penalty, and the violator is notified of the violation and the imposed penalty.</li>
    <li>All investigation procedures are documented and followed strictly according to policy.</li>
  </ol>

